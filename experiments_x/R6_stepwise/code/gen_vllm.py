"""Step-wise greedy generation with vLLM on exact token ids.

A job = (task, token-id prefix already generated by any model of the family, max_steps).  All models of a pair
share the Qwen3 tokenizer, so a handoff passes the exact token ids (no re-tokenization).  A step ends with the
first generated token whose text contains a newline (line-level steps; stop_token_ids, so the token is kept),
or after STEP_MAX_TOKENS tokens.  vLLM prefix caching reuses the model's own cache between its steps.
Per step: token ids, text, finish reason, confidence statistics (chosen-token logprob mean/min, top-5 entropy).

usage: python gen_vllm.py --model Qwen3-4B --jobs jobs.jsonl --out out.jsonl [--single_call]
job fields: job_id, task_id, prefix_ids (list[int]), max_steps (int or null = until EOS / budget)
--single_call: generate each job in one call without step stops (used to check that stepping is exact).
"""
import argparse, json, math, os, sys, time
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import *

ap = argparse.ArgumentParser()
ap.add_argument('--model', required=True); ap.add_argument('--jobs', required=True); ap.add_argument('--out', required=True)
ap.add_argument('--gpu_util', type=float, default=0.85); ap.add_argument('--tp', type=int, default=1)
ap.add_argument('--single_call', action='store_true')
args = ap.parse_args()

from vllm import LLM, SamplingParams
from vllm.inputs import TokensPrompt
from transformers import AutoTokenizer

path = model_path(args.model)
tok = AutoTokenizer.from_pretrained(path)
NL_IDS = newline_token_ids(tok)
TASKS = {t['task_id']: t for t in load_tasks()}
jobs = read_jsonl(args.jobs)
done = set()
if os.path.exists(args.out):
    done = {r['job_id'] for r in read_jsonl(args.out)}
jobs = [j for j in jobs if j['job_id'] not in done]
print(f'{args.model}: {len(jobs)} jobs to run ({len(done)} already done); {len(NL_IDS)} newline tokens', flush=True)
if not jobs:
    print('GENDONE', args.model, 0, flush=True); sys.exit(0)
llm = LLM(model=path, dtype='bfloat16', gpu_memory_utilization=args.gpu_util, enable_prefix_caching=True,
          max_model_len=4096, seed=0, tensor_parallel_size=args.tp, max_num_seqs=256)

chat_ids = {tid: tok(chat_prefix(tok, t['user']), add_special_tokens=False)['input_ids'] for tid, t in TASKS.items()}
state = [dict(job=j, ids=list(j['prefix_ids']), steps=[], finished=False, reason=None) for j in jobs]

def step_stats(out):
    lps, ents = [], []
    for tid, d in zip(out.token_ids, out.logprobs or []):
        if d is None: continue
        chosen = d.get(tid)
        if chosen is not None: lps.append(chosen.logprob)
        ps = [math.exp(v.logprob) for v in d.values()]
        ents.append(-sum(p * math.log(p) for p in ps if p > 0))
    return dict(lp_mean=(sum(lps) / len(lps)) if lps else 0.0, lp_min=min(lps) if lps else 0.0,
                ent_mean=(sum(ents) / len(ents)) if ents else 0.0, ent_max=max(ents) if ents else 0.0)

t0 = time.time(); it = 0
fout = open(args.out, 'a')
while True:
    active = [s for s in state if not s['finished']]
    if not active:
        break
    prompts, sps = [], []
    for s in active:
        budget = TOTAL_MAX_TOKENS - len(s['ids'])
        prompts.append(TokensPrompt(prompt_token_ids=chat_ids[s['job']['task_id']] + s['ids']))
        if args.single_call:
            sps.append(SamplingParams(temperature=0.0, max_tokens=max(1, budget), logprobs=5, seed=0))
        else:
            sps.append(SamplingParams(temperature=0.0, max_tokens=max(1, min(STEP_MAX_TOKENS, budget)), stop_token_ids=NL_IDS,
                                      logprobs=5, seed=0))
    outs = llm.generate(prompts, sps, use_tqdm=False)
    for s, o in zip(active, outs):
        c = o.outputs[0]
        ids = list(c.token_ids)
        st = dict(ids=ids, text=tok.decode(ids), n_tok=len(ids), finish=c.finish_reason,
                  n_prompt=len(o.prompt_token_ids), **step_stats(c))
        s['steps'].append(st); s['ids'] += ids
        newline_stop = (c.finish_reason == 'stop' and isinstance(c.stop_reason, int) and c.stop_reason in NL_IDS)
        if c.finish_reason == 'stop' and not newline_stop:
            s['finished'] = True; s['reason'] = 'eos'
        elif len(s['ids']) >= TOTAL_MAX_TOKENS:
            s['finished'] = True; s['reason'] = 'budget'
        elif len(s['steps']) >= MAX_STEPS:
            s['finished'] = True; s['reason'] = 'max_steps'
        elif s['job'].get('max_steps') is not None and len(s['steps']) >= s['job']['max_steps']:
            s['finished'] = True; s['reason'] = 'step_limit'
        if s['finished']:
            j = s['job']
            fout.write(json.dumps(dict(job_id=j['job_id'], task_id=j['task_id'], model=args.model, n_prefix=len(j['prefix_ids']),
                                       steps=s['steps'], full_ids=s['ids'], full_text=tok.decode(s['ids']), reason=s['reason'])) + '\n')
    fout.flush(); it += 1
    if it % 10 == 0 or not any(not s['finished'] for s in state):
        print(f'iter {it}: active {len(active)} -> {sum(not s["finished"] for s in state)}  {time.time()-t0:.0f}s', flush=True)
fout.close()
print('GENDONE', args.model, len(state), f'{time.time()-t0:.0f}s', flush=True)

